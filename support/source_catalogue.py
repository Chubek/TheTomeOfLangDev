#!/usr/bin/env python3
"""Regenerate the local source catalogue from source bytes and TeX source notes."""

import argparse
import hashlib
import re
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]
CATALOGUE = ROOT / "support" / "SOURCE-CATALOGUE.md"
SOURCE_NOTE = re.compile(r"^[ \t]*%+[ \t]*Source:[ \t]*(.+?)[ \t]*$", re.MULTILINE)
WHITESPACE = re.compile(rb"(?:[ \t\r\n\f]{2,}|[\t\r\n\f])")
READING_LENSES = {
    "Grammar": (b"lexical analysis", b"context-free grammar", b"parser combinator"),
    "Types": (b"type inference", b"type checking", b"type theory", b"effect system"),
    "Lisp": (b"common lisp", b"interlisp", b"lisp machine"),
    "Scheme": (b"scheme report", b"r7rs", b"scheme compiler", b"scheme implementation"),
    "Functional": (b"functional language", b"graph reduction", b"closure conversion"),
    "Design": (b"language design", b"domain-specific language", b"language evolution"),
    "IR": (b"intermediate representation", b"intermediate language", b"sea of nodes"),
    "SSA": (b"static single assignment", b"dataflow analysis", b"data-flow analysis"),
    "Assurance": (b"abstract interpretation", b"symbolic execution", b"translation validation"),
    "Instruction": (b"instruction selection", b"instruction set architecture", b"assemblers"),
    "Allocation": (b"register allocation", b"instruction scheduling", b"register pressure"),
    "Runtime": (b"virtual machine", b"garbage collection", b"operating system"),
    "Adaptive": (b"just-in-time", b"on-stack replacement", b"deoptimization", b"meta-tracing"),
}


def link(source):
    return f"[`{source}`](../sources/{quote(source)})"


def collect():
    sources = sorted(p for p in (ROOT / "sources").iterdir() if p.is_file())
    names = {p.name for p in sources}
    if not sources:
        raise ValueError("sources/ is empty")

    usages = defaultdict(set)
    for chapter in (ROOT / "chapters").glob("chapter-*.ltx"):
        for source in SOURCE_NOTE.findall(chapter.read_text(encoding="utf-8")):
            if source not in names:
                raise ValueError(f"{chapter.name}: unknown source {source!r}")
            usages[source].add(int(chapter.stem.removeprefix("chapter-")))

    groups = defaultdict(list)
    statuses = {}
    lenses_by_digest = {}
    digests = {}
    for path in sources:
        data = path.read_bytes()
        digest = hashlib.sha256(data).digest()
        digests[path.name] = digest
        groups[digest].append(path.name)
        if not data:
            status = "Empty"
        elif not data.decode("utf-8", errors="replace").strip():
            status = "Whitespace only"
        elif len(data) < 512:
            status = "Short extract (<512 bytes)"
        else:
            status = "Text present"
        statuses[path.name] = status
        if digest not in lenses_by_digest:
            text = WHITESPACE.sub(b" ", data.lower())
            lenses_by_digest[digest] = [
                lens for lens, phrases in READING_LENSES.items()
                if any(phrase in text for phrase in phrases)
            ]

    aliases = {source: group for group in groups.values() for source in group}
    lenses = {name: lenses_by_digest[digest] for name, digest in digests.items()}
    return sources, usages, statuses, aliases, list(groups.values()), lenses


def render():
    sources, usages, statuses, aliases, groups, lenses = collect()
    empty = sum(s == "Empty" for s in statuses.values())
    whitespace = sum(s == "Whitespace only" for s in statuses.values())
    short = sum(s.startswith("Short") for s in statuses.values())
    cited_groups = sum(any(source in usages for source in group) for group in groups)
    rows = [
        "# Local source catalogue",
        "",
        "Generated by `python3 support/source_catalogue.py`.",
        "See the Tome’s [bibliographic essay](../chapters/chapter-129.ltx) for reading",
        "strategies and examples of how to handle incomplete or mislabeled extracts.",
        "Chapter links below use stable file IDs, not the numbers printed in the PDF.",
        "",
        f"- **{len(sources):,} files**; **{len(groups):,} distinct byte sequences**",
        "  (not necessarily distinct publications).",
        f"- **{empty} empty**, **{whitespace} whitespace-only**, and **{short} other",
        "  extracts below 512 bytes**.",
        f"- **{len(usages):,} file names** have explicit chapter source notes;",
        f"  those notes cover **{cited_groups:,}** distinct byte sequences.",
        "",
        "A chapter link comes from a `% Source:` note in that chapter. An alias",
        "with identical bytes can share the reading reference, but does not",
        "provide independent evidence. Nonidentical scans or editions may",
        "still be versions of the same work. “Text present” is a size/content",
        "check, not a judgment about OCR quality, completeness, or relevance.",
        "A dash in the last column means no explicit source note was recorded.",
        "",
        "Reading lenses are exact phrase matches in the file contents after",
        "ASCII case folding and whitespace normalization. They are leads for",
        "finding further reading, **not** citations or subject classifications:",
        "a term in a bibliography can trigger a match and broken OCR can hide one.",
        "",
        "| Reading lens | Distinct matching texts | Search phrases |",
        "| --- | ---: | --- |",
    ]
    for lens, phrases in READING_LENSES.items():
        count = sum(lens in lenses[group[0]] for group in groups)
        queries = ", ".join(f"`{phrase.decode('ascii')}`" for phrase in phrases)
        rows.append(f"| {lens} | {count} | {queries} |")
    rows += [
        "",
        "| Local file | Extract status | Identical copy | Reading lenses | Chapter source notes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for path in sources:
        name = path.name
        group = aliases[name]
        canonical = group[0]
        exact = usages.get(name, set())
        via_alias = set().union(*(usages.get(alias, set()) for alias in group)) - exact
        chapters = [
            f"[{n}](../chapters/chapter-{n}.ltx){suffix}"
            for chapter_set, suffix in [(exact, ""), (via_alias, " (alias)")]
            for n in sorted(chapter_set)
        ]
        duplicate = link(canonical) if name != canonical else "—"
        rows.append(
            f"| {link(name)} | {statuses[name]} | {duplicate} | {', '.join(lenses[name]) or '—'} | "
            f"{', '.join(chapters) or '—'} |"
        )
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the catalogue is stale")
    args = parser.parse_args()
    try:
        result = render()
    except ValueError as error:
        parser.exit(1, f"{error}\n")
    if args.check:
        if not CATALOGUE.is_file() or CATALOGUE.read_text(encoding="utf-8") != result:
            parser.exit(1, "Catalogue is stale; run python3 support/source_catalogue.py\n")
    else:
        CATALOGUE.write_text(result, encoding="utf-8")


if __name__ == "__main__":
    main()
